"""Turns the PC app's wordmark into src/concepts/logo.hpp, raw RGBA pixels the PS5 app draws at the top of its screen.
The kit has no PNG decoder, so the pixels go into the app itself. Run it after changing the wordmark, then build:

    python console-app/make_logo.py      (needs Pillow; backend/.venv has it)
"""
from pathlib import Path

from PIL import Image

HEIGHT = 56  # on-screen pixels: drawn 1:1, so it stays sharp
here = Path(__file__).parent
im = Image.open(here.parent / "frontend" / "src" / "wordmark.png").convert("RGBA")
im = im.crop(im.getbbox()).resize((round(im.width * HEIGHT / im.height), HEIGHT), Image.LANCZOS)
data = im.tobytes()
rows = (", ".join(str(b) for b in data[i:i + 32]) for i in range(0, len(data), 32))
(here / "src" / "concepts" / "logo.hpp").write_text(
    "// Spela - The wordmark as RGBA pixels. Generated by console-app/make_logo.py; don't edit.\n"
    "#pragma once\n\n"
    f"constexpr int kLogoWidth = {im.width};\n"
    f"constexpr int kLogoHeight = {im.height};\n"
    "inline constexpr unsigned char kLogoRgba[] = {\n" + ",\n".join(rows) + "};\n",
    newline="\n")
print(f"wrote logo.hpp: {im.width}x{im.height}")
